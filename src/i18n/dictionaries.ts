const dicts: Record<Locale, Dict> = { en, si, ta };

export function translate(locale: Locale, key: DictKey): string {
  return dicts[locale][key] ?? en[key];
}

export function isDictKey(k: string): k is DictKey {
  return Object.prototype.hasOwnProperty.call(en, k);
}

export function isLocale(v: string | undefined): v is Locale {
  return v === "en" || v === "si" || v === "ta";
}
